def make_students(path: Path) -> None:
    workbook = Workbook()
    workbook.remove(workbook.active)
    for group, students in GROUPS.items():
        sheet = workbook.create_sheet(group)
        sheet.append(("Фамилия", "Имя"))
        sheet["A1"].font = sheet["B1"].font = Font(bold=True)
        sheet.column_dimensions["A"].width = sheet.column_dimensions["B"].width = 20
        for student in students:
            sheet.append(student)
    workbook.save(path)


def make_tickets(path: Path) -> None:
    document = Document()
    document.add_heading("Экзаменационные билеты по дисциплине «Программирование»", level=1)
    for number, questions in enumerate(TICKETS, start=1):
        document.add_paragraph(f"Билет {number}").runs[0].bold = True
        for index, question in enumerate(questions, start=1):
            document.add_paragraph(f"{index}. {question}")
        document.add_paragraph("")
    document.save(path)


